export type Key = keyof typeof dict.vi;

export function t(lang: Lang, key: Key): string {
  return dict[lang][key] ?? dict.vi[key] ?? key;
}

/** Path of the landing page for a language. */
export function homePath(lang: Lang): string {
  return lang === "en" ? "/en/" : "/";
}

export function appPath(lang: Lang, slug: string): string {
  return `${lang === "en" ? "/en" : ""}/apps/${slug}/`;
}

/** Article list: /bai-viet/ (vi), /en/articles/ (en). */
export function articlesPath(lang: Lang): string {
  return lang === "en" ? "/en/articles/" : "/bai-viet/";
}

export function articlePath(lang: Lang, slug: string): string {
  return `${articlesPath(lang)}${slug}/`;
}

/** 26/10/2026 (vi) — 26 Oct 2026 (en) */
export function formatDate(lang: Lang, iso: string | null | undefined): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "";
  if (lang === "vi") {
    const p = (n: number) => String(n).padStart(2, "0");
    const v = new Date(d.getTime() + 7 * 3600 * 1000);   // giờ Việt Nam, giống nhau khi build và trên trình duyệt
    return `${p(v.getUTCDate())}/${p(v.getUTCMonth() + 1)}/${v.getUTCFullYear()}`;
  }
  const m = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const v = new Date(d.getTime() + 7 * 3600 * 1000);
  return `${v.getUTCDate()} ${m[v.getUTCMonth()]} ${v.getUTCFullYear()}`;
}
